"""Generate EDIT_PLAN.md - the human-readable scene-specific editing plan.

Reads effects.json (creative intent) and scene_manifest.json (timing truth) and
emits one row per segment: where it sits, what is narrated, the emotional
intensity, the camera move, lighting, overlays, contextual sound and the
transition in/out. Regenerate whenever effects.json changes.

Run:  python _pipeline/cinematic/edit_plan.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
cfg = json.load(open(os.path.join(HERE, "effects.json"), encoding="utf-8"))
man = json.load(open(os.path.join(ROOT, "_pipeline", "scene_manifest.json"), encoding="utf-8"))
segs = man["segments"]

shots = cfg.get("sfx", [])
beds = cfg.get("beds", [])

# resolve phrase anchors so one-shots are attributed to the right segment
import re
_words = json.load(open(os.path.join(ROOT, "_pipeline", "transcript", "words.json"),
                        encoding="utf-8"))["words"]
_toks = [re.sub(r"[^a-z0-9']", "", w["w"].lower()) for w in _words]
_st = [w["start"] for w in _words]


def phrase_time(spec, k=0):
    pt = [re.sub(r"[^a-z0-9']", "", x.lower()) for x in spec["phrase"].split()]
    n = len(pt)
    hits = [i for i in range(len(_toks) - n + 1) if _toks[i:i + n] == pt]
    if k < len(hits):
        return _st[hits[k]] + spec.get("offset", 0)
    return None


def shot_times(ev):
    spec = ev["at"]
    if isinstance(spec, list):
        ts = []
        for c in spec:
            ts.append(c if isinstance(c, (int, float)) else c.get("t"))
        return ts
    if "phrase" in spec and "count" in spec:
        step = spec.get("interval", 0.32)
        return [t for k in range(spec["count"])
                if (t := phrase_time(spec, k)) is not None]
    if "phrase" in spec:
        t = phrase_time(spec)
        return [t] if t is not None else []
    return [spec.get("t")]


def fmt_time(spec):
    if isinstance(spec, (int, float)):
        return "t=%.2f" % spec
    if isinstance(spec, list):
        return "[" + ", ".join(fmt_time(x) for x in spec) + "]"
    if "phrase" in spec and "count" in spec:
        return '"%s" x%d' % (spec["phrase"], spec["count"])
    if "phrase" in spec:
        return '"%s"' % spec["phrase"]
    return "t=%.2f" % spec.get("t", 0)


def sfx_in(t0, t1):
    out = []
    for ev in shots:
        for t in shot_times(ev):
            if t is not None and t0 <= t <= t1:
                out.append("%s @%.2f" % (ev["name"], t))
                break
    return " + ".join(out) if out else "-"


def beds_in(t0, t1):
    out = []
    for b in beds:
        env = b.get("envelope", [])
        for (ta, va), (tb, vb) in zip(env, env[1:]):
            if max(va, vb) > 0.02 and tb > t0 and ta < t1:
                out.append(b["file"].replace(".wav", ""))
                break
    return ", ".join(dict.fromkeys(out)) if out else "-"


def overlays_of(s):
    return ", ".join(e["type"] for e in s.get("overlays", [])) or "-"


def light_of(s):
    l = s.get("light", {})
    bits = [k for k in ("flicker", "vignette", "warm") if k in l]
    if "dim" in l:
        bits.append("dim")
    return "+".join(bits) or "-"


def motion_of(s):
    m = s.get("motion")
    if not m:
        return "static (no motion)"
    f = m.get("focus")
    return "%s z%.2f%s" % (m["preset"], m.get("zoom", 1.0),
                           " focus(%s)" % ",".join("%.2f" % x for x in f) if f else "")


rows = []
for i, s in enumerate(segs):
    if s["kind"] == "card":
        rows.append((s["seg"], s["day"], s["start"], s["end"], "DAY %d card" % s["day"],
                     "-", "separator", "-", "-", "-",
                     "dip-through-black"))
        continue
    c = cfg["segments"].get(str(s["seg"]))
    if not c:
        rows.append((s["seg"], s["day"], s["start"], s["end"], s["image"], "-",
                     "legacy still", "-", "-", "-", "cut"))
        continue
    tr_in = "dip-in" if i > 0 and segs[i - 1]["kind"] == "card" else "cut"
    tr_out = "dip-out" if i + 1 < len(segs) and segs[i + 1]["kind"] == "card" else "cut"
    rows.append((s["seg"], s["day"], s["start"], s["end"], s["image"],
                 str(c.get("_intensity", "")), motion_of(c), light_of(c),
                 overlays_of(c), sfx_in(s["start"], s["end"]),
                 "%s / %s" % (tr_in, tr_out)))

out = ["# 10 Days - scene-specific editing plan",
       "",
       "Generated by `edit_plan.py` from `effects.json` (intent) + `scene_manifest.json` (timing).",
       "Intensity is emotional, 1 (quiet) to 5 (peak). Times are absolute seconds on the episode timeline.",
       "",
       "| seg | day | start-end | image | brief | int | camera | light | overlays | contextual sound | transition |",
       "|----:|----:|-----------|-------|-------|----:|--------|-------|----------|------------------|------------|"]

for sg, day, t0, t1, img, inten, mot, li, ov, sf, tr in rows:
    note = ""
    c = cfg["segments"].get(str(sg))
    if c:
        note = c.get("_note", "")
    note = note.split(" - ", 1)[-1] if " - " in note else note
    out.append("| %d | %d | %.2f-%.2f | %s | %s | %s | %s | %s | %s | %s | %s |"
               % (sg, day, t0, t1, img, note, inten, mot, li, ov, sf, tr))

out += ["", "## ambience beds (looping, whole-episode envelopes)", ""]
for b in beds:
    out.append("- `%s`  gain %.2f  envelope %s" % (b["file"], b.get("gain", 1.0),
                                                   b.get("envelope")))
out += ["", "## final cut", "",
        "Abrupt cut to black at `end.at` = %.2f s; all ambience hard-cuts with it." %
        cfg.get("end", {}).get("at", 0), ""]

open(os.path.join(HERE, "EDIT_PLAN.md"), "w", encoding="utf-8").write("\n".join(out))
print("wrote EDIT_PLAN.md (%d rows)" % len(rows))
